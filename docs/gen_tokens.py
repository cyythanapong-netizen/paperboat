"""The docs' design tokens: packages/shared/src/tokens.css (the app's one source) with its font
imports replaced by @font-face rules for the fonts in docs/_static/fonts, written to
docs/_static/tokens.css. The API reference (Sphinx) and docs/plan.html both link it, so a
change to a token changes the app and the docs together.

    python3 docs/gen_tokens.py            # write docs/_static/tokens.css
    python3 docs/gen_tokens.py --check    # fail if it is out of date (CI)
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "packages/shared/src/tokens.css"
TARGET = ROOT / "docs/_static/tokens.css"

# @fontsource's files, copied into docs/_static/fonts (no network at view time).
FONTS = [
    ("Geist Sans", "geist-sans", (400, 500, 600)),
    ("Geist Mono", "geist-mono", (400, 500)),
]


def build() -> str:
    faces = ""
    for family, name, weights in FONTS:
        for w in weights:
            faces += (
                f'@font-face {{ font-family: "{family}"; font-weight: {w}; font-display: swap; '
                f'src: url("fonts/{name}-latin-{w}-normal.woff2") format("woff2"); }}\n'
            )
    body = "\n".join(line for line in SOURCE.read_text().splitlines() if not line.startswith("@import"))
    return "/* Generated by docs/gen_tokens.py from packages/shared/src/tokens.css. Do not edit. */\n" + faces + body + "\n"


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            sys.exit("docs/_static/tokens.css is out of date: run python3 docs/gen_tokens.py")
        print("docs/_static/tokens.css is current")
        return
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
